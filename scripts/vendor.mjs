// Copies the browser dependencies that used to come from CDNs into vendor/.
// Run with: npm run vendor
import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nodeModules = path.join(root, 'node_modules');
const vendor = path.join(root, 'vendor');

const copy = async (source, target) => {
    const destination = path.join(vendor, target);
    await mkdir(path.dirname(destination), { recursive: true });
    await cp(path.join(nodeModules, source), destination);
};

await rm(vendor, { recursive: true, force: true });

// Three.js ESM build and the two addons the game imports.
await copy('three/build/three.module.min.js', 'three/three.module.min.js');
await copy('three/build/three.core.min.js', 'three/three.core.min.js');
await copy('three/examples/jsm/utils/BufferGeometryUtils.js', 'three/addons/utils/BufferGeometryUtils.js');
await copy('three/examples/jsm/controls/PointerLockControls.js', 'three/addons/controls/PointerLockControls.js');
await copy('three/LICENSE', 'three/LICENSE');

// Font Awesome: solid and regular fonts are used by the game.
await copy('@fortawesome/fontawesome-free/css/fontawesome.min.css', 'fontawesome/css/fontawesome.min.css');
await copy('@fortawesome/fontawesome-free/css/solid.min.css', 'fontawesome/css/solid.min.css');
await copy('@fortawesome/fontawesome-free/css/regular.min.css', 'fontawesome/css/regular.min.css');
await copy('@fortawesome/fontawesome-free/webfonts/fa-solid-900.woff2', 'fontawesome/webfonts/fa-solid-900.woff2');
await copy('@fortawesome/fontawesome-free/webfonts/fa-regular-400.woff2', 'fontawesome/webfonts/fa-regular-400.woff2');
await copy('@fortawesome/fontawesome-free/LICENSE.txt', 'fontawesome/LICENSE.txt');

// Mona Sans variable font (Latin normal + italic).
await copy('@fontsource-variable/mona-sans/files/mona-sans-latin-wght-normal.woff2', 'fonts/mona-sans-latin-wght-normal.woff2');
await copy('@fontsource-variable/mona-sans/files/mona-sans-latin-wght-italic.woff2', 'fonts/mona-sans-latin-wght-italic.woff2');
await copy('@fontsource-variable/mona-sans/LICENSE', 'fonts/LICENSE');

const latinRange = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';

await writeFile(path.join(vendor, 'fonts/mona-sans.css'), `/* Generated by scripts/vendor.mjs */
@font-face {
  font-family: 'Mona Sans';
  font-style: normal;
  font-display: swap;
  font-weight: 200 900;
  src: url('./mona-sans-latin-wght-normal.woff2') format('woff2-variations');
  unicode-range: ${latinRange};
}

@font-face {
  font-family: 'Mona Sans';
  font-style: italic;
  font-display: swap;
  font-weight: 200 900;
  src: url('./mona-sans-latin-wght-italic.woff2') format('woff2-variations');
  unicode-range: ${latinRange};
}
`);

console.log('Vendored Three.js, Font Awesome, and Mona Sans into vendor/.');
